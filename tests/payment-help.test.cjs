const assert=require('node:assert/strict');
const help=require('../src/customer/payment-help.js'),bridge=require('../src/shared/payment-bridge.js'),core=require('../src/customer/mobile-core.js'),model=require('../models/random-forest.json');
const p=core.assess(model,250,2);p.bank='sbi';
assert.equal(help.prompt(p),'');assert.throws(()=>help.respond(p,'Suspicious'),/completed/);
const wallet={balance:2000,payments:[p]};core.authorise(wallet,p,'123456');
const balance=wallet.balance,decision=p.assessment.decision;
help.respond(p,'Not sure');assert(help.guide(p).includes('Let’s check it together.'));
help.respond(p,'Suspicious','pressure');const reported=bridge.record(p);
assert.equal(reported.customerReport.answer,'Suspicious');
assert.equal(reported.status,'Paid');assert.equal(reported.decision,decision);assert.equal(wallet.balance,balance);
assert.equal(bridge.normalise(reported).customerReport.reason,'pressure');
const old={...reported};delete old.customerReport;
assert.equal(bridge.combine([old],[reported])[0].customerReport.answer,'Suspicious');
assert.equal(bridge.combine([reported],[old])[0].customerReport.answer,'Suspicious');
assert(!JSON.stringify(reported).includes('123456'));
assert.equal(bridge.feedback({answer:'malicious',reason:'pressure',updatedAt:new Date().toISOString()}),null);
assert.throws(()=>help.respond(p,'confirmed fraud'),/valid/);
assert(help.summary(p).includes('not an official bank or police complaint'));
assert(help.summary(p).includes('demo ID, not a bank UTR'));
assert(help.guide(p).includes('tel:1930'));
assert(help.guide(p).includes('https://cybercrime.gov.in/'));
assert(help.guide(p).includes('no real money moved'));
help.respond(p,'Looks right');assert(help.prompt(p).includes('Your response:'));
assert(help.guide(null).includes('Choose a completed payment'));
console.log('PASS: completed-payment gating, three safety responses, concern reasons, shared round-trip, stale report retention, unchanged funds/risk/status, official guidance and demo-only incident summary.');
