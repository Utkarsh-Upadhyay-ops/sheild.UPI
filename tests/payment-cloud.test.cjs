const assert=require('node:assert/strict');
const {create}=require('../src/shared/payment-cloud.js');
const bridge=require('../src/shared/payment-bridge.js');
const core=require('../src/customer/mobile-core.js');
const model=require('../models/random-forest.json');
(async()=>{
  const payment=core.assess(model,431,3);payment.bank='sbi';
  const wallet={balance:1000,payments:[payment]};
  const pending=bridge.record(payment);let release, calls=[];
  const cloud=create({fetch:async(url,options)=>{calls.push(JSON.parse(options.body));if(calls.length===1)await new Promise(r=>release=r);return {ok:true,json:async()=>({records:calls.at(-1).records})};}});
  cloud.publish([pending]);
  core.authorise(wallet,payment,'123456');const paid=bridge.record(payment);
  cloud.publish([paid]);release();
  await new Promise(r=>setTimeout(r,30));await cloud.flush();cloud.stop();
  assert.equal(calls.length,2);assert.equal(calls[0].records[0].status,'Ready to pay');assert.equal(calls[1].records[0].status,'Paid');
  assert.equal(bridge.combine([pending],[paid])[0].status,'Paid');
  assert.equal(bridge.combine([paid],[pending])[0].status,'Paid');
  assert.equal(bridge.normalise(paid).id,payment.id);
  assert.deepEqual(bridge.normalise(paid),paid);
  let feeds=[],status=[];
  const reader=create({fetch:async()=>({ok:true,json:async()=>({records:[paid]})}),onRecords:r=>feeds.push(r),onStatus:s=>status.push(s)});
  await reader.poll();await reader.poll();reader.stop();
  assert.equal(feeds.length,1);assert.equal(feeds[0][0].status,'Paid');
  const injected=structuredClone(payment);injected.assessment.signals.pin='do-not-upload';
  injected.assessment.network=[{sender:'person-1',receiver:'person-2',amount:4,timestamp:payment.timestamp,secret:'do-not-upload'}];
  assert(!JSON.stringify(bridge.record(injected)).includes('do-not-upload'));
  const failed=create({fetch:async()=>{throw Error('offline');},onStatus:s=>status.push(s)});
  failed.publish([paid]);await new Promise(r=>setTimeout(r,10));failed.stop();
  assert(status.some(s=>s.includes('will retry')));
  console.log('PASS: in-flight pending/paid updates, terminal-status merge, clean cloud round-trip, independent history feed, unchanged-feed stability, no extra signal/graph data and offline retry.');
})().catch(e=>{console.error(e);process.exitCode=1;});
