const assert = require('node:assert/strict');
const model = require('../models/random-forest.json');
const {assess,settle} = require('../src/customer/mobile-core.js');
const low=assess(model,250,1,'normal');
assert.equal(low.assessment.decision,'Allow');
const verify=assess(model,250,2,'verify');
assert.equal(verify.assessment.decision,'Verify');
const high=assess(model,250,3,'ring');
assert.equal(high.assessment.decision,'Flag');
const wallet={balance:1000,payments:[low,verify,high]};
assert.throws(()=>settle(wallet,high),/held/);
assert.throws(()=>settle(wallet,verify),/Verify/);
assert.equal(wallet.balance,1000);
settle(wallet,low);
assert.equal(wallet.balance,750);
settle(wallet,low);
assert.equal(wallet.balance,750);
settle(wallet,verify,true);
assert.equal(wallet.balance,500);
assert.equal(assess(model,1.1,1).amount,1.1);
assert.throws(()=>assess(model,-5,1));
assert.throws(()=>assess(model,1.111,1));
assert.throws(()=>assess(model,100,0));
console.log('PASS: real model low/verify/high scenarios, high-risk hold, verification gating, single debit and amount validation.');

const {banks,initialiseWallet,linkBank,selectBank}=require('../src/customer/mobile-core.js');
const fs=require('node:fs'),path=require('node:path');
assert.equal(banks.length,12);
for(const bank of banks)assert(fs.existsSync(path.join(__dirname,'../public',bank.logo)));
const bankWallet={balance:1000,payments:[]};
initialiseWallet(bankWallet);
linkBank(bankWallet,'hdfc');
assert.equal(bankWallet.selectedBank,'hdfc');
assert.equal(bankWallet.accounts.sbi.balance,1000);
const bankPayment=assess(model,250,1);
bankPayment.bank='hdfc';
bankWallet.payments.push(bankPayment);
selectBank(bankWallet,'sbi');
settle(bankWallet,bankPayment);
assert.equal(bankWallet.balance,1000);
assert.equal(bankWallet.accounts.hdfc.balance,24750);
linkBank(bankWallet,'hdfc');
assert.equal(bankWallet.balance,24750);
settle(bankWallet,bankPayment);
assert.equal(bankWallet.balance,24750);
assert.throws(()=>linkBank(bankWallet,'unknown'));
assert.throws(()=>selectBank(bankWallet,'axis'));
console.log('PASS: 12 local bank logo assets, account migration, separate balances, duplicate-add preservation, correct-bank debit and bank selection.');

const intelligence=require('../models/graph-and-anomaly.json'),temporal=require('../models/temporal-graph.json');
for(const scenario of ['normal','verify','ring','cycle']) {
 const p=assess(model,250,1,scenario,{intelligence,temporal,behavior:{available:false}});
 assert(Number.isFinite(p.assessment.intelligence.anomalyScore));
 assert(p.assessment.temporalGraph.accounts.length>=2);
 assert(p.assessment.timings.allModelsMs>=0);
 assert(p.assessment.timings.pipelineTotalMs>=p.assessment.timings.allModelsMs);
 assert.equal(p.assessment.network.filter(e=>e.candidate).length,1);
 if(scenario==='ring'||scenario==='cycle')assert.equal(p.assessment.decision,'Flag');
 console.log('Integrated '+scenario+': '+p.assessment.decision+'; models '+p.assessment.timings.allModelsMs.toFixed(2)+' ms; pipeline '+p.assessment.timings.pipelineTotalMs.toFixed(2)+' ms');
}
const drift=assess(model,250,1,'normal',{intelligence,temporal,behavior:{available:true,deviation:4}});
assert.notEqual(drift.assessment.decision,'Allow');
console.log('PASS: RF, Isolation Forest, temporal GNN, directed candidate graph, cycle/ring holds and measured behavior drift are integrated.');

const {authorise}=require('../src/customer/mobile-core.js');
const pinPayment=assess(model,250,1),pinWallet={balance:1000,payments:[pinPayment]};
assert.throws(()=>authorise(pinWallet,pinPayment,'654321'),/demo PIN/);
assert.throws(()=>authorise(pinWallet,pinPayment,'12345'),/demo PIN/);
assert.equal(pinWallet.balance,1000);
authorise(pinWallet,pinPayment,'123456');
assert.equal(pinWallet.balance,750);
authorise(pinWallet,pinPayment,'123456');
assert.equal(pinWallet.balance,750);
const heldPin=assess(model,250,2,'ring');pinWallet.payments.push(heldPin);
assert.throws(()=>authorise(pinWallet,heldPin,'123456'),/held/);
const verifyPin=assess(model,250,2,'verify');pinWallet.payments.push(verifyPin);
assert.throws(()=>authorise(pinWallet,verifyPin,'123456'),/Verify/);
assert.equal(pinWallet.balance,750);
authorise(pinWallet,verifyPin,'123456',true);
assert.equal(pinWallet.balance,500);
assert(!JSON.stringify(pinWallet).includes('123456'));
console.log('PASS: demo PIN required, wrong/partial PIN preserves balance, verification and high-risk gates stay enforced, one debit, no PIN stored.');
