const assert=require('node:assert/strict');
const bridge=require('../src/shared/payment-bridge.js');
const core=require('../src/customer/mobile-core.js');
const model=require('../models/random-forest.json');
const p=core.assess(model,250,1);p.bank='sbi';
const wallet={balance:1000,payments:[p]};
let records=bridge.read(JSON.stringify(wallet));
assert.equal(records[0].status,'Ready to pay');assert.equal(records[0].settled,false);
const sample={id:'TX-001001',source:'Generated sample',timestamp:new Date(Date.now()-1000).toISOString()};
let ledger=bridge.merge([sample],records);
assert.equal(ledger.length,2);
core.authorise(wallet,p,'123456');
records=bridge.read(JSON.stringify(wallet));
ledger=bridge.merge(ledger,records);
assert.equal(ledger.length,2);
assert.equal(ledger[0].status,'Paid');assert.equal(ledger[0].settled,true);
assert.equal(ledger[0].id,p.id);assert.equal(ledger[0].risk,p.assessment.modelScore);
assert.equal(ledger[0].bank,'sbi');assert.equal(ledger[0].receiver,'person-1');
assert.equal(bridge.merge(ledger,records).length,2);
assert.equal(bridge.read('{broken'),null);
assert.equal(bridge.read(JSON.stringify({payments:[{id:'PAY-bad-123'}]})).length,0);
const held=core.assess(model,250,2,'ring');
assert.equal(bridge.record(held).settled,false);
assert.equal(bridge.record({...held,status:'Paid'}),null);
assert(!JSON.stringify(records).includes('123456'));
console.log('PASS: pending-to-paid status propagation, preserved reference/risk/bank, duplicate-free merge, sample retention, held-payment gating and corrupt-record handling.');
